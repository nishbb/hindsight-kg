"""M4: dossiers for the 20 QIAGEN test variants, committed to results/qiagen_20/.

Usage: python scripts/m4_qiagen.py [--as-of latest]
"""

from __future__ import annotations

import argparse
import json

from kggc.utils import RESULTS_DIR
from kggc.variant_dossier.cli import run
from kggc.variant_dossier.haplotype import render_haplotype

QIAGEN_20 = [
    "rs9807334", "rs121913529", "rs72921001", "rs17822931", "rs334",
    "rs987870", "rs429358", "rs3827760", "rs113993960", "rs4988235",
    "rs28934578", "rs17004038", "rs12913832", "rs6025", "rs713598",
    "rs7412", "rs80357713", "rs1426654", "rs1799963", "rs1801133",
]  # fmt: skip


def slim(d: dict) -> dict:
    """Drop bulky PMID lists from the committed JSON; cited values stay verifiable."""
    d = json.loads(json.dumps(d, default=str))
    d["literature"]["pmids_in_scope"] = d["literature"]["pmids_in_scope"][:50]
    for rid, rec in d["records"].items():
        if rid.startswith("LitVar2:"):
            rec["data"]["n_pmids"] = len(rec["data"]["pmids"])
            rec["data"]["pmids"] = rec["data"]["pmids"][:50]
    return d


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--as-of", default="latest")
    args = ap.parse_args()
    out = RESULTS_DIR / ("qiagen_20" if args.as_of == "latest" else f"qiagen_20_asof_{args.as_of}")
    res = run(QIAGEN_20, args.as_of, out)
    for d in res["dossiers"]:
        (out / f"{d['rsid_query']}.json").write_text(json.dumps(slim(d), indent=1))
    for h in res["haplotypes"]:
        name = "+".join(h["rsids"])
        for rid, rec in h["records"].items():
            if rid.startswith("LitVar2-overlap"):
                rec["data"]["shared_pmids"] = rec["data"]["shared_pmids"][:50]
        (out / f"haplotype_{name}.json").write_text(json.dumps(h, indent=1, default=str))

    ok = [s for s in res["summary"] if s["status"] == "ok"]
    lines = [
        "# QIAGEN 20-variant dossier report",
        "",
        f"Evidence as of: **{args.as_of}**. Generated by `scripts/m4_qiagen.py`. "
        "Every sentence below carries a citation to a stored record, and each citation was "
        "re-checked against the raw record by `kggc.variant_dossier.verify`.",
        "",
        f"Completed dossiers: {len(ok)} of {len(QIAGEN_20)}.",
        "",
        "| rsID | current ID | type | gene (VEP) | alt alleles | claims | citation validity | conflicts flagged | confidence |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for d in res["dossiers"]:
        v = d["verification"]
        lines.append(
            f"| {d['rsid_query']} | {d['rsid_current']} | {d['variant_type']} | {', '.join(d['genes']['vep']) or '(none)'} | "
            f"{len(d['alleles'])} | {v['n_claims']} | {v['n_citations_valid']}/{v['n_citations']} | "
            f"{len([k for k in d['conflicts'] if k['type'] != 'classification_changed_over_time'])} | {d['bottom_line']['confidence']} |"
        )
    failed = [s for s in res["summary"] if s["status"] != "ok"]
    if failed:
        lines += ["", "Failed:", ""] + [f"* {s['rsid']}: {s['error']}" for s in failed]
    if res["haplotypes"]:
        lines += ["", "## Joint interpretation (haplotypes detected automatically)", ""]
        for h in res["haplotypes"]:
            lines += ["```text", render_haplotype(h).rstrip(), "```", ""]
    lines += ["", "## Per-variant dossiers", ""]
    for d in res["dossiers"]:
        lines += [
            f"### {d['rsid_query']}",
            "",
            "```text",
            (out / f"{d['rsid_query']}.txt").read_text().rstrip(),
            "```",
            "",
        ]
    (out / "qiagen_20_report.md").write_text("\n".join(lines) + "\n")
    tot_c = sum(d["verification"]["n_citations"] for d in res["dossiers"])
    tot_ok = sum(d["verification"]["n_citations_valid"] for d in res["dossiers"])
    stats = {
        "as_of": args.as_of,
        "n_variants": len(QIAGEN_20),
        "n_complete": len(ok),
        "n_claims": sum(d["verification"]["n_claims"] for d in res["dossiers"]),
        "n_citations": tot_c,
        "citation_validity_rate": tot_ok / tot_c if tot_c else None,
        "n_uncited_claims": sum(d["verification"]["n_uncited_claims"] for d in res["dossiers"]),
        "n_sentences_without_citation": sum(
            d["verification"]["rendered_text"]["n_without_citation"] for d in res["dossiers"]
        ),
        "temporal_violations": sum(
            len(d["verification"]["temporal_violations"]) for d in res["dossiers"]
        ),
        "haplotype_pairs": [h["rsids"] for h in res["haplotypes"]],
    }
    (out / "stats.json").write_text(json.dumps(stats, indent=1))
    print(stats)


if __name__ == "__main__":
    main()
